"""Set up a managed Postgres for the first deploy: the six roles, and who owns the database. Run once, from your machine.

    $env:TJ_SETUP_URL = "postgresql://<the host's admin user>:<its password>@<external host>/<database>"
    python -m tradejournal.pg.provision_hosted --out .env.hosted --app-host <the host's private address>

The address with its password is read from the environment, never from the command line, and nothing secret is printed.
The roles get random passwords that are written to ``--out`` (a file git ignores), as ready-to-paste settings for the web
service. Running it again keeps the passwords already in that file, so it is safe to repeat.

What it does, in this order (doc 03 section 1, ``docs/runbooks/deploy.md`` section 1):

1. creates ``tj_owner``, ``app_rw``, ``app_login``, ``app_webhook``, ``app_sweep`` and ``app_admin`` (plain login roles:
   not a superuser, no BYPASSRLS, no CREATEDB, no CREATEROLE);
2. makes ``tj_owner`` the owner of the database and of its ``public`` schema, so the migrations can build everything and the
   web service's own role can change nothing about the schema;
3. checks the result and prints a summary.

The administrator account must be allowed to create roles and databases' owners (CREATEROLE and CREATEDB, or a superuser).
With ``--migrate`` it then runs the migrations as ``tj_owner``. Without it they are a separate step
(``python -m tradejournal.pg.migrate``, which reads ``TJ_OWNER_URL`` from the output file).
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit

import psycopg
from psycopg import sql

from . import migrate as pg_migrate
from .provision import APP_ROLE, OWNER_ROLE, SYSTEM_ROLES, apply_roles, random_password

ROLES = [OWNER_ROLE, APP_ROLE, *SYSTEM_ROLES.values()]
# The setting each role's connection string is stored under. The first group belongs on the web service; the second never
# does (the owner can change the schema, the sweep and the operator role are for other processes).
WEB_KEYS = {APP_ROLE: "TJ_DATABASE_URL", "app_login": "TJ_LOGIN_DATABASE_URL"}
OTHER_KEYS = {
    "app_admin": "TJ_ADMIN_DATABASE_URL",
    "app_sweep": "TJ_SWEEP_DATABASE_URL",
    "app_webhook": "TJ_WEBHOOK_DATABASE_URL",
    OWNER_ROLE: "TJ_OWNER_URL",
}
URL_KEYS = {**WEB_KEYS, **OTHER_KEYS}
SESSION_KEY = "TJ_SESSION_SECRET"  # signs the per-session CSRF tokens: 64 hexadecimal characters, fixed across deploys


class SetupError(Exception):
    """The database cannot be set up as asked; the message says what to change."""


def url_for(setup_url: str, role: str, password: str, *, host: str | None = None) -> str:
    """The connection string for ``role``: the setup address with its user and password swapped. With ``host`` (the host's
    private address) the query string (such as ``sslmode``) is dropped: it was for the public address."""
    parts = urlsplit(setup_url)
    name = host or parts.hostname
    port = f":{parts.port}" if parts.port and not host else ""
    query = f"?{parts.query}" if parts.query and not host else ""
    return f"{parts.scheme}://{quote(role, safe='')}:{quote(password, safe='')}@{name}{port}{parts.path}{query}"


def read_settings(path: Path) -> dict[str, str]:
    """Every ``KEY=value`` in a file this tool wrote, commented out or not."""
    found: dict[str, str] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            key, _, value = line.lstrip("# ").partition("=")
            if value and " " not in key.strip():
                found[key.strip()] = value.strip()
    return found


def read_passwords(path: Path) -> dict[str, str]:
    """The role passwords already in a file this tool wrote, so a second run changes nothing."""
    settings = read_settings(path)
    found: dict[str, str] = {}
    for role, key in URL_KEYS.items():
        parts = urlsplit(settings.get(key, ""))
        if parts.username == role and parts.password:
            found[role] = unquote(parts.password)
    return found


def render_file(setup_url: str, passwords: dict[str, str], app_host: str | None, *, session_secret: str) -> str:
    def line(role: str, key: str, *, host: str | None, comment: bool = False) -> str:
        return ("# " if comment else "") + f"{key}={url_for(setup_url, role, passwords[role], host=host)}"

    lines = [
        "# Generated by tradejournal.pg.provision_hosted. Contains passwords: never commit it, paste it, or send it.",
        "",
        "# The web service. Paste these into its environment settings.",
        *(line(role, key, host=app_host) for role, key in WEB_KEYS.items()),
        f"{SESSION_KEY}={session_secret}",
        "",
        "# NOT for the web service. Each is a different process's credential. Uncomment where noted.",
        "# The schema owner: runs the migrations from your machine (python -m tradejournal.pg.migrate), at this public address.",
        line(OWNER_ROLE, OTHER_KEYS[OWNER_ROLE], host=None, comment=True),
        "# The operator tools: add to the web service only after you have made yourself an operator (deploy.md section 7).",
        line("app_admin", OTHER_KEYS["app_admin"], host=app_host, comment=True),
        "# The daily deletion sweep job.",
        line("app_sweep", OTHER_KEYS["app_sweep"], host=app_host, comment=True),
        "# Reserved for billing; nothing reads it yet.",
        line("app_webhook", OTHER_KEYS["app_webhook"], host=app_host, comment=True),
        "",
    ]
    return "\n".join(lines)


def check_administrator(conn: psycopg.Connection) -> str:
    me, superuser, create_role, create_db = conn.execute(
        "SELECT rolname, rolsuper, rolcreaterole, rolcreatedb FROM pg_roles WHERE rolname = current_user"
    ).fetchone()
    if not superuser and not (create_role and create_db):
        missing = " and ".join(name for name, ok in (("CREATEROLE", create_role), ("CREATEDB", create_db)) if not ok)
        raise SetupError(
            f"The account in TJ_SETUP_URL ({me}) does not have {missing}, so it cannot create the roles or hand the "
            "database to tj_owner. Ask the host's support whether an administrator account with those rights exists; "
            "this can change the choice of host (design doc 02)."
        )
    return me


def setup(conn: psycopg.Connection, passwords: dict[str, str]) -> None:
    """Make the roles and give tj_owner the database and the ``public`` schema. Idempotent."""
    me = check_administrator(conn)
    database = conn.execute("SELECT current_database()").fetchone()[0]
    apply_roles(conn, passwords, reset_attributes=False)  # verify() catches a role whose attributes are wrong
    # Handing a database over needs the right to become the new owner. A role's creator may grant that to itself.
    conn.execute(
        sql.SQL("GRANT {} TO {} WITH SET TRUE, INHERIT FALSE").format(sql.Identifier(OWNER_ROLE), sql.Identifier(me))
    )
    schema_owner = conn.execute(
        "SELECT pg_get_userbyid(nspowner) FROM pg_namespace WHERE nspname = 'public'"
    ).fetchone()[0]
    # The schema first: changing its owner needs CREATE on the database, which the old owner of the database has and a
    # role that has just handed the database over does not.
    # Since PG 15 the schema belongs to "pg_database_owner", which is whoever owns the database: now tj_owner.
    if schema_owner not in (OWNER_ROLE, "pg_database_owner"):
        conn.execute(sql.SQL("ALTER SCHEMA public OWNER TO {}").format(sql.Identifier(OWNER_ROLE)))
    owner = conn.execute(
        "SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname = current_database()"
    ).fetchone()[0]
    if owner != OWNER_ROLE:
        conn.execute(
            sql.SQL("ALTER DATABASE {} OWNER TO {}").format(sql.Identifier(database), sql.Identifier(OWNER_ROLE))
        )


def verify(conn: psycopg.Connection) -> list[str]:
    """What is still wrong, in words. Empty when every role is plain and tj_owner owns the database."""
    problems = []
    for role in ROLES:
        row = conn.execute(
            "SELECT rolsuper, rolbypassrls, rolcreatedb, rolcreaterole, rolcanlogin FROM pg_roles WHERE rolname = %s",
            (role,),
        ).fetchone()
        if row is None:
            problems.append(f"{role} does not exist")
        elif row[:4] != (False, False, False, False) or not row[4]:
            problems.append(f"{role} has the wrong attributes")
    owner = conn.execute(
        "SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname = current_database()"
    ).fetchone()[0]
    if owner != OWNER_ROLE:
        problems.append(f"the database is owned by {owner}, not {OWNER_ROLE}")
    schema = conn.execute("SELECT pg_get_userbyid(nspowner) FROM pg_namespace WHERE nspname = 'public'").fetchone()[0]
    if schema not in (OWNER_ROLE, "pg_database_owner"):
        problems.append(f"the public schema is owned by {schema}")
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--out", type=Path, required=True, help="where to write the settings (use a name starting .env)"
    )
    parser.add_argument(
        "--app-host",
        help="the address the web service reaches the database at, if it differs from TJ_SETUP_URL's (a private address)",
    )
    parser.add_argument(
        "--migrate", action="store_true", help="also run the migrations, as tj_owner, once the roles are set"
    )
    args = parser.parse_args(argv)

    setup_url = os.environ.get("TJ_SETUP_URL")
    if not setup_url:
        print("TJ_SETUP_URL is not set (see --help)", file=sys.stderr)
        return 2
    if not urlsplit(setup_url).path.strip("/"):
        print("TJ_SETUP_URL must end with the database's name", file=sys.stderr)
        return 2

    known = read_passwords(args.out)
    session_secret = read_settings(args.out).get(SESSION_KEY) or secrets.token_hex(32)
    passwords = {role: known.get(role) or random_password() for role in ROLES}
    try:
        with psycopg.connect(setup_url, autocommit=True) as conn:
            setup(conn, passwords)
            problems = verify(conn)
    except SetupError as error:
        print(error, file=sys.stderr)
        return 1
    except psycopg.Error as error:
        # The server's message names the problem and never contains the password.
        print(f"The database refused a step: {str(error).strip().splitlines()[0]}", file=sys.stderr)
        return 1
    if problems:
        print("Set up, but not as intended: " + "; ".join(problems), file=sys.stderr)
        return 1

    args.out.write_text(
        render_file(setup_url, passwords, args.app_host, session_secret=session_secret), encoding="utf-8"
    )
    print(
        f"six roles ready, {OWNER_ROLE} owns the database. Wrote {args.out} (contains passwords; keep it out of git)."
    )
    if args.migrate:
        try:
            applied = pg_migrate.migrate(url_for(setup_url, OWNER_ROLE, passwords[OWNER_ROLE]))
        except psycopg.Error as error:
            print(f"The migrations stopped: {str(error).strip().splitlines()[0]}", file=sys.stderr)
            return 1
        print(f"migrations applied: {', '.join(applied)}" if applied else "migrations: nothing to apply")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
